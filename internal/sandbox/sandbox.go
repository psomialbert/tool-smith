// Package sandbox wraps a command so Tier 0/2 tools only ever execute inside
// an OS sandbox (§7 invariant). macOS uses a Seatbelt profile via
// sandbox-exec; Linux uses bubblewrap. If no sandbox mechanism is available
// the caller must refuse to run — never fall back to unsandboxed execution.
package sandbox

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
)

// Perms are the per-tool sandbox grants. The zero value is the strict
// default: no network, writes confined to CWD+TMP. Grants are declared in the
// tool's manifest and are part of what a human reviews at adoption.
type Perms struct {
	Network    bool     // allow network egress (default: denied)
	WritePaths []string // absolute paths granted write access beyond CWD+TMP
}

// sortedWritePaths returns WritePaths sorted, for a deterministic profile.
func (p Perms) sortedWritePaths() []string {
	w := append([]string(nil), p.WritePaths...)
	sort.Strings(w)
	return w
}

// seatbeltProfile builds the macOS Seatbelt policy. Deny-by-default for the
// dimensions we care about; network denial is dropped only when granted.
func seatbeltProfile(p Perms) string {
	var b strings.Builder
	b.WriteString(";; Generated by smith. sandbox-exec is deprecated-but-functional (spec §10).\n")
	b.WriteString("(version 1)\n(allow default)\n")
	if !p.Network {
		b.WriteString("(deny network*)\n")
	}
	b.WriteString("(deny file-write*)\n")
	b.WriteString(`(allow file-write* (subpath (param "CWD")))` + "\n")
	b.WriteString(`(allow file-write* (subpath (param "TMP")))` + "\n")
	for _, w := range p.sortedWritePaths() {
		fmt.Fprintf(&b, "(allow file-write* (subpath %q))\n", w)
	}
	b.WriteString(`(allow file-write-data
  (literal "/dev/null")
  (literal "/dev/zero")
  (literal "/dev/dtracehelper")
  (literal "/dev/tty")
  (regex #"^/dev/fd/"))` + "\n")
	return b.String()
}

// profileName is stable per permission set so profiles are written once and
// reused (no per-run temp files that would leak across syscall.Exec). The
// common strict/network cases keep readable names; any write-path grant hashes
// the profile so distinct capability sets never collide on one cached file.
func profileName(p Perms) string {
	if len(p.WritePaths) == 0 {
		if p.Network {
			return "net.sb"
		}
		return "default.sb"
	}
	h := sha256.Sum256([]byte(seatbeltProfile(p)))
	return "p-" + hex.EncodeToString(h[:])[:12] + ".sb"
}

func ensureProfile(profilesDir string, p Perms) (string, error) {
	if err := os.MkdirAll(profilesDir, 0o755); err != nil {
		return "", err
	}
	path := filepath.Join(profilesDir, profileName(p))
	want := seatbeltProfile(p)
	if cur, err := os.ReadFile(path); err != nil || string(cur) != want {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			return "", err
		}
	}
	return path, nil
}

// WriteDefaultProfile installs the strict default profile (smith init).
func WriteDefaultProfile(profilesDir string) (string, error) {
	return ensureProfile(profilesDir, Perms{})
}

// Functional reports whether a strict sandbox actually works on this host by
// running a no-op command inside it. Presence of the sandbox binary is not
// enough — some CI hosts ship bwrap but forbid the namespace setup it needs.
// Returns nil on success, or a descriptive error (fails closed).
func Functional(profilesDir string) error {
	bin := map[string]string{"darwin": "sandbox-exec", "linux": "bwrap"}[runtime.GOOS]
	if bin == "" {
		return fmt.Errorf("no sandbox available on %s", runtime.GOOS)
	}
	if _, err := exec.LookPath(bin); err != nil {
		return fmt.Errorf("%s not found on PATH", bin)
	}
	work, err := os.MkdirTemp("", "smith-probe-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(work)
	tru, err := exec.LookPath("true")
	if err != nil {
		tru = "/usr/bin/true"
	}
	argv, err := Command(filepath.Join(work, "profiles"), work, Perms{}, []string{tru})
	if err != nil {
		return fmt.Errorf("sandbox setup failed: %w", err)
	}
	cmd := exec.Command(argv[0], argv[1:]...)
	cmd.Dir = work
	if out, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("sandbox present but not functional: %v: %s", err, out)
	}
	return nil
}

// envAllowlist is the only parent environment that reaches a sandboxed
// tool. Everything else — tokens, cloud creds, session identifiers — stays
// out: the sandbox blocks network, but env -> file-in-CWD -> later read is
// a real exfiltration channel.
var envAllowlist = []string{"PATH", "TMPDIR", "LANG", "LC_ALL", "LC_CTYPE", "TERM", "TZ"}

// linuxScratchHome lives inside the tmpfs bwrap mounts over /tmp; the
// matching --dir flag in Command creates it inside the sandbox.
const linuxScratchHome = "/tmp/smith-home"

// Env builds the sanitized environment for a sandboxed run. HOME points at
// a scratch dir (inside TMP, so the profile allows writes there). passEnv
// names extra parent vars the caller explicitly chose to forward.
func Env(passEnv []string) ([]string, error) {
	var scratchHome string
	if runtime.GOOS == "linux" {
		scratchHome = linuxScratchHome
	} else {
		var err error
		if scratchHome, err = os.MkdirTemp("", "smith-scratch-home-"); err != nil {
			return nil, err
		}
	}
	env := []string{"HOME=" + scratchHome, "SMITH_SANDBOX=1"}
	for _, k := range envAllowlist {
		if v, ok := os.LookupEnv(k); ok {
			env = append(env, k+"="+v)
		}
	}
	for _, k := range passEnv {
		k = strings.TrimSpace(k)
		if k == "" {
			continue
		}
		v, ok := os.LookupEnv(k)
		if !ok {
			return nil, fmt.Errorf("--pass-env %s: not set in parent environment", k)
		}
		env = append(env, k+"="+v)
	}
	return env, nil
}

// Command returns the full argv that runs `argv` sandboxed under perms, with
// writes confined to workDir (empty = current dir) and TMP, or an error if no
// sandbox mechanism exists on this machine.
func Command(profilesDir, workDir string, perms Perms, argv []string) ([]string, error) {
	switch runtime.GOOS {
	case "darwin":
		if _, err := exec.LookPath("sandbox-exec"); err != nil {
			return nil, fmt.Errorf("sandbox-exec not found; refusing to run quarantined tool unsandboxed")
		}
		profile, err := ensureProfile(profilesDir, perms)
		if err != nil {
			return nil, err
		}
		cwd := workDir
		if cwd == "" {
			if cwd, err = os.Getwd(); err != nil {
				return nil, err
			}
		}
		if r, err := filepath.EvalSymlinks(cwd); err == nil {
			cwd = r
		}
		tmp := os.TempDir()
		if r, err := filepath.EvalSymlinks(tmp); err == nil {
			tmp = r
		}
		out := []string{"sandbox-exec", "-f", profile, "-D", "CWD=" + cwd, "-D", "TMP=" + tmp}
		return append(out, argv...), nil
	case "linux":
		if _, err := exec.LookPath("bwrap"); err != nil {
			return nil, fmt.Errorf("bwrap (bubblewrap) not found; refusing to run quarantined tool unsandboxed")
		}
		cwd := workDir
		if cwd == "" {
			var err error
			if cwd, err = os.Getwd(); err != nil {
				return nil, err
			}
		}
		out := []string{
			"bwrap",
			"--ro-bind", "/", "/",
			"--dev", "/dev",
			"--tmpfs", "/tmp",
			"--dir", linuxScratchHome,
			"--bind", cwd, cwd,
			"--die-with-parent",
		}
		for _, w := range perms.sortedWritePaths() {
			out = append(out, "--bind", w, w) // rw bind for a granted write path
		}
		if !perms.Network {
			out = append(out, "--unshare-net")
		}
		return append(out, argv...), nil
	default:
		return nil, fmt.Errorf("no sandbox mechanism for %s; refusing to run quarantined tool", runtime.GOOS)
	}
}
